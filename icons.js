function psIcon(name, size = 18) {
  const paths = PS_ICONS[name];
  if (!paths) return '';
  return `<svg width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${paths}</svg>`;
}

// Relleno automático de <span data-icon="...">
(function () {
  const fill = () => {
    document.querySelectorAll('[data-icon]').forEach((el) => {
      if (el.dataset.iconDone) return;
      const svg = psIcon(el.dataset.icon, parseInt(el.dataset.iconSize, 10) || 18);
      if (svg) { el.innerHTML = svg; el.dataset.iconDone = '1'; }
    });
  };
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', fill);
  else fill();
})();
